/**
 * 被行内代码吞掉的加粗定界修复：损坏形态 `**文字 \`code**\``（闭合 **
 * 被吸进反引号内部）在严格 CommonMark 下渲染为字面源码——行首 ** 不成对、
 * code 内的 ** 是普通字符。Typora 的 emphasis 配对跨越 code span 边界
 * （宽松行为）把它渲染成加粗，用户预期与之对齐。
 *
 * 粘贴/导入前把闭定界挪回反引号外：`**文字 \`code\`**`。
 * 只修"明确指纹"：开 ** 在 code 前、闭 ** 贴 code 内容尾部且后随闭反引号；
 * 正常配对形态（code 开反引号后是闭反引号）天然不匹配，零误伤。
 * 源头说明：该形态历史上由"展开态泄漏"产生（已修），此修复让旧坏文本
 * 重新粘贴时自愈。
 */
export function fixSwallowedEmphasis(md: string): string {
  return md.replace(/\*\*([^`\n]*)`([^`\n]*)\*\*`/g, '**$1`$2`**')
}
